const generateSeats = (total: number, brokenCount: number = 1) => {
  const seats = [];
  const cols = 8;
  for (let i = 1; i <= total; i++) {
    const row = Math.ceil(i / cols);
    const col = ((i - 1) % cols) + 1;
    seats.push({
      id: `PC-${i.toString().padStart(2, '0')}`,
      name: `PC-${i.toString().padStart(2, '0')}`,
      row,
      col,
      status: (i === brokenCount ? 'maintenance' : (i % 7 === 0 ? 'reserved' : 'available')) as 'available' | 'reserved' | 'maintenance',
    });
  }
  return seats;
};

